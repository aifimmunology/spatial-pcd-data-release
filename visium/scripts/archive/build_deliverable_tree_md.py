#!/usr/bin/env python3
"""Render a content-tree .md preview of an assembled GEO deliverable, under the
final upload naming convention -- BEFORE any packaging/upload.

Mirrors the look of data/visium-zip-trees/*.md (the source-zip trees) but for the
*output* side: it walks an assembled sample tree (produced by assemble_geo_run.py)
and rewrites every path under the chosen deliverable name so the .md shows exactly
what the uploaded zip will contain, with sizes.

Naming convention (lowercase, hyphenated, searchable by visium / TIS / EXP /
geo-ready): the deliverable id names ONLY the top folder (and the zip built from
it). Files inside keep their bare Space Ranger names, e.g.
    visium_tis06377-001_exp-01092_geo-ready/
        gene_expression/raw/raw_feature_bc_matrix.h5
    -> packaged as visium_tis06377-001_exp-01092_geo-ready.zip

LOCAL ONLY: reads the assembled tree from disk and writes a .md. No upload.

Usage:
    python build_deliverable_tree_md.py [DELIVERABLE_ID]
    # default: DELIVERABLE_ID=visium_tis06377-001_exp-01092_geo-ready
    # (the assembled-tree folder name, == the zip name without .zip)
"""

import os
import sys

BASE = "/home/workspace/PCD_data/visium/data/visium-data"
BUILD_ROOT = os.path.join(BASE, "geo_build")
OUT_DIR = "/home/workspace/PCD_data/visium/data/visium-deliverable-trees"


def human(n):
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1024 or unit == "GB":
            return f"{n:.1f}{unit}" if unit != "B" else f"{n}B"
        n /= 1024


def render_tree(root, deliverable_id):
    """Walk `root` and return (lines, n_files, total_bytes) for a tree whose top
    dir is `deliverable_id`. Files keep their on-disk (bare) names."""
    lines = [f"{deliverable_id}/"]
    n_files = 0
    total = 0

    def walk(path, prefix):
        nonlocal n_files, total
        entries = sorted(os.listdir(path),
                         key=lambda e: (os.path.isfile(os.path.join(path, e)), e))
        for i, e in enumerate(entries):
            full = os.path.join(path, e)
            last = i == len(entries) - 1
            connector = "└── " if last else "├── "
            if os.path.isdir(full):
                lines.append(f"{prefix}{connector}{e}/")
                walk(full, prefix + ("    " if last else "│   "))
            else:
                sz = os.path.getsize(full)
                n_files += 1
                total += sz
                lines.append(f"{prefix}{connector}{e}  ({human(sz)})")

    walk(root, "")
    return lines, n_files, total


def main():
    deliverable = (sys.argv[1] if len(sys.argv) > 1
                   else "visium_tis06377-001_exp-01092_geo-ready")

    root = os.path.join(BUILD_ROOT, deliverable)
    if not os.path.isdir(root):
        print(f"ERROR: assembled tree not found: {root}\n  run assemble_geo_run.py first.")
        return

    tree, n_files, total = render_tree(root, deliverable)
    zip_name = f"{deliverable}.zip"

    md = []
    md.append(f"# {zip_name}")
    md.append("")
    md.append("PREVIEW of the reformatted GEO deliverable for this run, under the")
    md.append("final upload naming convention. Generated by")
    md.append("`scripts/build_deliverable_tree_md.py` from the assembled tree")
    md.append("(`scripts/assemble_geo_run.py`). No upload has occurred.")
    md.append("")
    md.append(f"- Deliverable folder / zip: `{deliverable}`")
    md.append("- File names inside: bare Space Ranger names (folder carries the id)")
    md.append(f"- Package: one zip per sample -> `{zip_name}`")
    md.append(f"- Entries: {n_files} files")
    md.append(f"- Uncompressed total: {human(total)}")
    md.append("")
    md.append("Layout follows `reference/final_visium_structure_resolved.txt`.")
    md.append("Decisions baked in: ADT_CST_bridge omitted (no source in any run);")
    md.append("H&E = CytAssist image (EVOS sourcing deferred, Task 6).")
    md.append("")
    md.append("```")
    md.extend(tree)
    md.append("```")

    os.makedirs(OUT_DIR, exist_ok=True)
    out_path = os.path.join(OUT_DIR, f"{deliverable}.md")
    with open(out_path, "w") as f:
        f.write("\n".join(md) + "\n")

    print("\n".join(md))
    print(f"\nWrote: {out_path}")


if __name__ == "__main__":
    main()
