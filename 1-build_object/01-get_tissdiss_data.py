import hisepy as hp
from concurrent.futures import ThreadPoolExecutor, as_completed

# resolve partial names to full store paths
pcd_sptl = hp.list_files_in_project_store('PCD_Spatial')
full_names = pcd_sptl["name"].dropna().tolist()

full_files_list = []
for partial in files_list:
    matches = [f for f in full_names if partial in f]
    if not matches:
        print(f"No match for: {partial}")
    elif len(matches) > 1:
        print(f"Multiple matches for: {partial} -> {matches}")
    else:
        full_files_list.append(matches[0])

# same file matched by two partials -> keep one
full_files_list = list(dict.fromkeys(full_files_list))

def download_one_file(file_name):
    ok = hp.download_from_project_store(
        store_name="PCD_Spatial",
        file_name=file_name,
    )
    if not ok:  # returns a bool, not a path
        raise RuntimeError("download returned False")
    return file_name

max_workers = 8
results = []
errors = []
with ThreadPoolExecutor(max_workers=max_workers) as executor:
    future_to_file = {
        executor.submit(download_one_file, file_name): file_name
        for file_name in full_files_list
    }
    for future in as_completed(future_to_file):
        file_name = future_to_file[future]
        try:
            results.append(future.result())
            print(f"done: {file_name}")
        except Exception as exc:
            errors.append((file_name, exc))
            print(f"failed: {file_name}: {exc}")

print(f"{len(results)} ok, {len(errors)} failed, {len(full_files_list)} requested")